/* ---------- SHARED HELPERS ---------- */

function getSavedLanguage() {
  try {
    const language = localStorage.getItem("codemind-language");
    return language === "fa" || language === "en" ? language : null;
  } catch (error) {
    return null;
  }
}

function saveLanguage(language) {
  try {
    localStorage.setItem("codemind-language", language);
  } catch (error) {
    // The page continues to work if storage is unavailable.
  }
}


function updateTextElements(dictionary) {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (!Object.prototype.hasOwnProperty.call(dictionary, key)) {
      return;
    }

    const translation = dictionary[key];

    // Preserve highlighted spans in headings.
    if (translation.includes("<span>")) {
      element.innerHTML = translation;
    } else {
      element.textContent = translation;
    }
  });
}


/* ---------- HOMEPAGE LANGUAGE ---------- */

function applyHomeLanguage(language) {
  const selectedLanguage = homeTranslations[language] ? language : "en";
  const dictionary = homeTranslations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = selectedLanguage === "fa" ? "rtl" : "ltr";

  updateTextElements(dictionary);

  const button = document.getElementById("languageButton");

  if (button) {
    button.textContent = selectedLanguage === "fa" ? "EN" : "فا فارسی";
    button.setAttribute(
      "aria-label",
      selectedLanguage === "fa"
        ? "Switch to English"
        : "تغییر زبان به فارسی"
    );
  }

  document.title =
    selectedLanguage === "fa"
      ? "CodeMind | ساخت فراتر از محدودیت‌ها"
      : "CodeMind | Build Beyond Limits";

  saveLanguage(selectedLanguage);
}


/* ---------- RESUME LANGUAGE ---------- */

function applyResumeLanguage(language) {
  const selectedLanguage = resumeTranslations[language] ? language : "fa";
  const dictionary = resumeTranslations[selectedLanguage];

  document.documentElement.lang = selectedLanguage;
  document.documentElement.dir = selectedLanguage === "fa" ? "rtl" : "ltr";

  updateTextElements(dictionary);

  const toggle = document.getElementById("languageToggle");

  if (toggle) {
    toggle.textContent = selectedLanguage === "fa" ? "EN" : "FA";
    toggle.setAttribute(
      "aria-label",
      selectedLanguage === "fa"
        ? "Switch to English"
        : "تغییر زبان به فارسی"
    );
  }

  document.title =
    selectedLanguage === "fa"
      ? "رزومه | CodeMind"
      : "Resume | CodeMind";

  saveLanguage(selectedLanguage);
}


/* ---------- INITIALIZATION ---------- */

document.addEventListener("DOMContentLoaded", () => {
  const currentYear = new Date().getFullYear();

  const homeYear = document.getElementById("year");
  if (homeYear) {
    homeYear.textContent = currentYear;
  }

  const resumeYear = document.getElementById("currentYear");
  if (resumeYear) {
    resumeYear.textContent = currentYear;
  }

  const isHomepage = document.getElementById("languageButton") !== null;
  const isResume = document.getElementById("languageToggle") !== null;

  const savedLanguage = getSavedLanguage();

  if (isHomepage) {
    applyHomeLanguage(savedLanguage || "en");

    const button = document.getElementById("languageButton");

    button.addEventListener("click", () => {
      const nextLanguage =
        document.documentElement.lang === "fa" ? "en" : "fa";

      applyHomeLanguage(nextLanguage);
    });

  } else if (isResume) {
    applyResumeLanguage(savedLanguage || "fa");

    const button = document.getElementById("languageToggle");

    button.addEventListener("click", () => {
      const nextLanguage =
        document.documentElement.lang === "fa" ? "en" : "fa";

      applyResumeLanguage(nextLanguage);
    });
  }
});

